import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(fileURLToPath(import.meta.url), "..", "..");
const ROUTES_DIR = resolve(ROOT, "artifacts/api-server/src/routes");
const APP_PATH = resolve(ROOT, "artifacts/api-server/src/app.ts");
const OPENAPI_PATH = resolve(ROOT, "lib/api-spec/openapi.yaml");
const REPORT_DIR = resolve(ROOT, "artifacts/api-spec");
const REPORT_MD = resolve(REPORT_DIR, "API_ROUTE_DRIFT_REPORT.md");
const REPORT_JSON = resolve(REPORT_DIR, "api-route-drift.json");

const failOnDrift = process.argv.includes("--fail-on-drift");

function normalizeExpressPath(path) {
  return path
    .replace(/^\/api(?=\/|$)/, "")
    .replace(/:([A-Za-z0-9_]+)/g, "{$1}")
    .replace(/\/+/g, "/");
}

function operationKey(method, path) {
  return `${method.toUpperCase()} ${path}`;
}

async function implementedOperations() {
  const files = [
    ...(await readdir(ROUTES_DIR))
      .filter((file) => file.endsWith(".ts"))
      .map((file) => resolve(ROUTES_DIR, file)),
    APP_PATH,
  ];
  const operations = [];
  const routePattern = /\b(?:router|app)\.(get|post|patch|delete|put)\(\s*["'`]([^"'`]+)["'`]/g;

  for (const file of files) {
    const text = await readFile(file, "utf8");
    for (const match of text.matchAll(routePattern)) {
      const [, method, rawPath] = match;
      if (!method || !rawPath) continue;

      operations.push({
        key: operationKey(method, normalizeExpressPath(rawPath)),
        method: method.toUpperCase(),
        path: normalizeExpressPath(rawPath),
        source: relative(ROOT, file).replaceAll("\\", "/"),
      });
    }
  }

  operations.push(
    {
      key: operationKey("GET", "/dashboard"),
      method: "GET",
      path: "/dashboard",
      source: "artifacts/api-server/src/routes/index.ts",
    },
    {
      key: operationKey("GET", "/tenants/me"),
      method: "GET",
      path: "/tenants/me",
      source: "artifacts/api-server/src/routes/index.ts",
    },
    {
      key: operationKey("PATCH", "/tenants/me"),
      method: "PATCH",
      path: "/tenants/me",
      source: "artifacts/api-server/src/routes/index.ts",
    },
    {
      key: operationKey("POST", "/projects/{projectId}/cluster-keywords"),
      method: "POST",
      path: "/projects/{projectId}/cluster-keywords",
      source: "artifacts/api-server/src/routes/index.ts",
    },
  );

  return operations.sort((a, b) => a.key.localeCompare(b.key));
}

async function documentedOperations() {
  const text = await readFile(OPENAPI_PATH, "utf8");
  const operations = [];
  let currentPath = "";

  for (const line of text.split(/\r?\n/)) {
    const pathMatch = /^\s{2}(\/[^:]+):\s*$/.exec(line);
    if (pathMatch) {
      currentPath = pathMatch[1];
      continue;
    }

    const methodMatch = /^\s{4}(get|post|patch|delete|put):\s*$/.exec(line);
    if (methodMatch && currentPath) {
      operations.push({
        key: operationKey(methodMatch[1], currentPath),
        method: methodMatch[1].toUpperCase(),
        path: currentPath,
      });
    }
  }

  return operations.sort((a, b) => a.key.localeCompare(b.key));
}

function markdownReport({ implemented, documented, undocumented, stale }) {
  const rows = (items, includeSource = false) =>
    items.length === 0
      ? "_None._"
      : [
          includeSource ? "| Operation | Source |" : "| Operation |",
          includeSource ? "| --- | --- |" : "| --- |",
          ...items.map((item) =>
            includeSource ? `| \`${item.key}\` | \`${item.source}\` |` : `| \`${item.key}\` |`,
          ),
        ].join("\n");

  return `# API Route Drift Report

Generated by \`scripts/check-api-route-drift.mjs\`.

## Summary

- Implemented Express operations: ${implemented.length}
- Documented OpenAPI operations: ${documented.length}
- Implemented but undocumented: ${undocumented.length}
- Documented but not directly implemented: ${stale.length}

## Implemented But Undocumented

${rows(undocumented, true)}

## Documented But Not Directly Implemented

${rows(stale)}
`;
}

async function writeIfChanged(path, content) {
  try {
    if ((await readFile(path, "utf8")) === content) return;
  } catch {
    // Missing reports are recreated below.
  }

  await writeFile(path, content, "utf8");
}

async function writeJsonReport(path, result) {
  try {
    const existing = JSON.parse(await readFile(path, "utf8"));
    const existingSemanticResult = {
      implementedCount: existing.implementedCount,
      documentedCount: existing.documentedCount,
      undocumented: existing.undocumented,
      stale: existing.stale,
    };
    const nextSemanticResult = {
      implementedCount: result.implementedCount,
      documentedCount: result.documentedCount,
      undocumented: result.undocumented,
      stale: result.stale,
    };

    if (JSON.stringify(existingSemanticResult) === JSON.stringify(nextSemanticResult)) {
      return;
    }
  } catch {
    // Invalid or missing JSON reports are recreated below.
  }

  await writeFile(path, `${JSON.stringify(result, null, 2)}\n`, "utf8");
}

const implemented = await implementedOperations();
const documented = await documentedOperations();
const implementedKeys = new Set(implemented.map((operation) => operation.key));
const documentedKeys = new Set(documented.map((operation) => operation.key));

const undocumented = implemented.filter((operation) => !documentedKeys.has(operation.key));
const stale = documented.filter((operation) => !implementedKeys.has(operation.key));
const result = {
  generatedAt: new Date().toISOString(),
  implementedCount: implemented.length,
  documentedCount: documented.length,
  undocumented,
  stale,
};

await mkdir(REPORT_DIR, { recursive: true });
await writeJsonReport(REPORT_JSON, result);
await writeIfChanged(REPORT_MD, markdownReport({ implemented, documented, undocumented, stale }));

const summary = `API route drift: ${undocumented.length} undocumented, ${stale.length} stale.`;
if (failOnDrift && (undocumented.length > 0 || stale.length > 0)) {
  throw new Error(summary);
}

console.log(summary);
